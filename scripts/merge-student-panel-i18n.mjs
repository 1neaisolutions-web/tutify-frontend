function translateValue(value, lang) {
  if (typeof value !== 'string') return value;
  const map = STRING_MAP[lang];
  return map?.[value] ?? value;
}

function translateTree(obj, lang) {
  if (typeof obj === 'string') return translateValue(obj, lang);
  if (Array.isArray(obj)) return obj.map((v) => translateTree(v, lang));
  const out = {};
  for (const [k, v] of Object.entries(obj)) {
    out[k] = translateTree(v, lang);
  }
  return out;
}

