function translateString(s, lang) {
  if (typeof s !== 'string') return s
  let out = s
  const wordMap = maps[lang]
  for (const [en, tr] of Object.entries(wordMap)) {
    out = out.split(en).join(tr)
  }
  for (const [en, tr] of phraseMaps[lang] || []) {
    out = out.split(en).join(tr)
  }
  return out
}

function translateDeep(obj, lang) {
  if (typeof obj === 'string') return translateString(obj, lang)
  if (Array.isArray(obj)) return obj.map((v) => translateDeep(v, lang))
  if (obj && typeof obj === 'object') {
    const out = {}
    for (const [k, v] of Object.entries(obj)) out[k] = translateDeep(v, lang)
    return out
  }
  return obj
}

function deepMerge(target, source) {
  const out = { ...target }
  for (const [k, v] of Object.entries(source)) {
    if (v && typeof v === 'object' && !Array.isArray(v) && target[k] && typeof target[k] === 'object') {
      out[k] = deepMerge(target[k], v)
    } else {
      out[k] = v
    }
  }
  return out
}

for (const lang of ['es-ES', 'fr-FR', 'pt-BR', 'de-DE']) {
  const path = join(localesDir, `${lang}.json`)
  const data = JSON.parse(readFileSync(path, 'utf8'))
  const patch = translateDeep(pick, lang)
  const merged = deepMerge(data, patch)
  writeFileSync(path, JSON.stringify(merged, null, 2) + '\n', 'utf8')
  console.log('Updated', lang)
}
