function autoTranslate(s, langKey) {
  const sentences = SENTENCE[langKey]
  if (sentences[s]) return sentences[s]
  let r = s
  const words = WORD[langKey]
  const sorted = Object.keys(words).sort((a, b) => b.length - a.length)
  for (const k of sorted) {
    r = r.split(k).join(words[k])
  }
  return r
}

function translateTree(source, langKey) {
  if (typeof source === 'string') return autoTranslate(source, langKey)
  const out = {}
  for (const [k, v] of Object.entries(source)) {
    out[k] = translateTree(v, langKey)
  }
  return out
}

